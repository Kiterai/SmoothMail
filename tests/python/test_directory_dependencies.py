"""Check source-directory layering without requiring Doxygen or a C++ SDK."""

import re
import unittest
from pathlib import Path, PurePosixPath


ROOT = Path(__file__).resolve().parents[2]


def directory_dependencies(sources, generated_includes=()):
    edges = set()
    for source, content in sources.items():
        parent = PurePosixPath(source).parent
        for include in re.findall(r'^\s*#\s*include\s*"([^"]+)"', content, re.M):
            candidates = ((parent / include).as_posix(), "src/" + include)
            target = next((path for path in candidates if path in sources), None)
            if target is None:
                if include in generated_includes:
                    continue
                raise ValueError(f"{source}: unresolved project include {include}")
            directory = PurePosixPath(target).parent.as_posix()
            if parent.as_posix() != directory:
                edges.add((parent.as_posix(), directory))
    return edges


def find_cycle(edges):
    graph = {}
    for source, target in sorted(edges):
        graph.setdefault(source, set()).add(target)
    visited, active = set(), []

    def visit(node):
        if node in active:
            return active[active.index(node):] + [node]
        if node in visited:
            return None
        active.append(node)
        for target in sorted(graph.get(node, ())):
            cycle = visit(target)
            if cycle:
                return cycle
        active.pop()
        visited.add(node)
        return None

    for node in sorted(graph):
        cycle = visit(node)
        if cycle:
            return cycle
    return None


class DirectoryDependencyTests(unittest.TestCase):
    def test_local_and_root_includes_ignore_external_and_same_directory(self):
        sources = {
            "src/mail/a.cpp": '#include "a.h"\n#include "core/b.h"\n#include <QObject>\n',
            "src/mail/a.h": '#include "core/b.h"\n',
            "src/core/b.h": "",
        }
        self.assertEqual(directory_dependencies(sources), {("src/mail", "src/core")})

    def test_missing_project_include_is_not_silently_ignored(self):
        with self.assertRaisesRegex(ValueError, "unresolved project include"):
            directory_dependencies({"src/a.cpp": '#include "missing.h"'})

    def test_explicit_generated_header_is_not_a_source_directory(self):
        self.assertEqual(directory_dependencies(
            {"src/core/a.h": '#include "oauthdefaults.h"'}, {"oauthdefaults.h"}), set())

    def test_detects_indirect_cycle_and_accepts_diamond(self):
        self.assertEqual(find_cycle({("core", "mail"), ("mail", "storage"), ("storage", "core")}),
                         ["core", "mail", "storage", "core"])
        self.assertIsNone(find_cycle({("app", "mail"), ("app", "storage"),
                                     ("mail", "core"), ("storage", "core")}))

    def test_source_directories_are_acyclic_and_follow_layering(self):
        sources = {path.relative_to(ROOT).as_posix(): path.read_text(encoding="utf-8")
                   for path in (ROOT / "src").rglob("*") if path.suffix in (".cpp", ".h")}
        # Generated by cmake/OAuthDefaults.cmake, not another source layer.
        edges = directory_dependencies(sources, {"oauthdefaults.h"})
        cycle = find_cycle(edges)
        self.assertIsNone(cycle, f"Directory dependency cycle: {cycle}")
        allowed = {
            "src": {"src/app", "src/core", "src/ui"},
            "src/app": {"src/core", "src/mail", "src/storage", "src/mime", "src/oauth", "src/ui"},
            "src/ui": {"src/core", "src/mail", "src/storage", "src/mime", "src/oauth"},
            "src/mail": {"src/core", "src/storage", "src/mime", "src/oauth"},
            "src/storage": {"src/core", "src/mime", "src/oauth"},
            "src/mime": {"src/core"},
            "src/oauth": set(),
            "src/core": set(),
        }
        for source, target in sorted(edges):
            self.assertIn(target, allowed.get(source, set()), f"{source} must not depend on {target}")


if __name__ == "__main__":
    unittest.main()
